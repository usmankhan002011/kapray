create table if not exists public.storage_delete_queue (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  bucket_id text not null,
  object_path text not null,
  source_table text not null default 'unknown',
  source_id bigint,
  source_key text,
  attempts integer not null default 0,
  locked_at timestamptz,
  locked_by text,
  processed_at timestamptz,
  last_error text,
  constraint storage_delete_queue_path_not_blank check (
    btrim(bucket_id) <> '' and btrim(object_path) <> ''
  ),
  constraint storage_delete_queue_attempts_nonnegative check (attempts >= 0)
);

