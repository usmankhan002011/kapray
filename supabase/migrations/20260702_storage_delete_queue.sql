create or replace function public.enqueue_storage_delete(
  p_bucket_id text,
  p_object_path text,
  p_source_table text default 'unknown',
  p_source_id bigint default null,
  p_source_key text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if nullif(btrim(coalesce(p_bucket_id, '')), '') is null then
    return;
  end if;

  if nullif(btrim(coalesce(p_object_path, '')), '') is null then
    return;
  end if;

  insert into public.storage_delete_queue (
    bucket_id,
    object_path,
    source_table,
    source_id,
    source_key
  )
  values (
    btrim(p_bucket_id),
    btrim(p_object_path),
    coalesce(nullif(btrim(coalesce(p_source_table, '')), ''), 'unknown'),
    p_source_id,
    nullif(btrim(coalesce(p_source_key, '')), '')
  )
  on conflict (bucket_id, object_path)
  do update set
    updated_at = now(),
    source_table = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.source_table
      else excluded.source_table
    end,
    source_id = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.source_id
      else excluded.source_id
    end,
    source_key = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.source_key
      else excluded.source_key
    end,
    attempts = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.attempts
      else 0
    end,
    locked_at = null,
    locked_by = null,
    processed_at = null,
    last_error = null;
end;
$$;

revoke all on function public.enqueue_storage_delete(text, text, text, bigint, text)
from public;

create or replace function public.enqueue_storage_delete_prefix(
  p_bucket_id text,
  p_prefix text,
  p_source_table text default 'unknown',
  p_source_id bigint default null,
  p_source_key text default null
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer := 0;
begin
  if nullif(btrim(coalesce(p_bucket_id, '')), '') is null then
    return 0;
  end if;

  if nullif(btrim(coalesce(p_prefix, '')), '') is null then
    return 0;
  end if;

  insert into public.storage_delete_queue (
    bucket_id,
    object_path,
    source_table,
    source_id,
    source_key
  )
  select
    storage_object.bucket_id,
    storage_object.name,
    coalesce(nullif(btrim(coalesce(p_source_table, '')), ''), 'unknown'),
    p_source_id,
    nullif(btrim(coalesce(p_source_key, '')), '')
  from storage.objects as storage_object
  where storage_object.bucket_id = btrim(p_bucket_id)
    and storage_object.name like btrim(p_prefix) || '%'
  on conflict (bucket_id, object_path)
  do update set
    updated_at = now(),
    source_table = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.source_table
      else excluded.source_table
    end,
    source_id = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.source_id
      else excluded.source_id
    end,
    source_key = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.source_key
      else excluded.source_key
    end,
    attempts = case
      when public.storage_delete_queue.processed_at is null
        then public.storage_delete_queue.attempts
      else 0
    end,
    locked_at = null,
    locked_by = null,
    processed_at = null,
    last_error = null;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.enqueue_storage_delete_prefix(text, text, text, bigint, text)
from public;

create or replace function public.queue_deleted_product_storage()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product_code text;
  v_prefix text;
begin
  v_product_code := nullif(btrim(coalesce(old.product_code, '')), '');

  if old.vendor_id is null or v_product_code is null then
    return old;
  end if;

  v_prefix := 'vendors/' || old.vendor_id::text || '/products/' ||
    v_product_code || '/';

  perform public.enqueue_storage_delete_prefix(
    'vendor_images',
    v_prefix,
    'products',
    old.id,
    v_product_code
  );

  return old;
end;
$$;

drop trigger if exists trg_products_queue_storage_delete
on public.products;

create trigger trg_products_queue_storage_delete
after delete on public.products
for each row
execute function public.queue_deleted_product_storage();

